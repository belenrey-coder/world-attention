"""Step 6: write docs/PROFILE.md from the interim outputs, moments and exports."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import pyarrow.parquet as pq

sys.path.insert(0, str(Path(__file__).parent))
from common import DOCS, INTERIM, WORK, load_json  # noqa: E402


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(r[c]).replace("|", "/") for c in cols) + " |")
    return "\n".join(out)


def main():
    L = []
    t = pq.read_table(INTERIM / "trends.parquet",
                      columns=["location", "level", "country_code", "start_time_utc", "end_time_utc", "query_norm"]).to_pandas()
    checks = load_json(INTERIM / "timestamp_checks.json")
    comb = load_json(WORK / "combine_summary.json", {})
    st = pd.read_parquet(WORK / "string_topics.parquet")
    log = load_json(Path(__file__).resolve().parents[1] / "cache" / "claude" / "batches.json", {"batches": []})

    L.append("# Data profile\n")
    L.append("_Generated by `pipeline/06_profile.py`. Re-run it after any change to steps 2–5._\n")
    if comb.get("claude_labels", 0) < st.important.sum() * 0.9 or comb.get("strings_with_qid", 0) == 0:
        L.append("> **Provisional.** The Claude labels cover only the 500-string test batch, and Wikidata "
                 "links are not populated yet (see “Open issues” in DECISIONS.md). Merge statistics will "
                 "change after both layers run in full.\n")

    # --- rows and coverage
    L.append("## Rows and coverage\n")
    L.append(f"- Raw rows: **{checks['rows_raw']:,}**; dropped US metro (numeric) codes: "
             f"{checks['rows_metro_dropped']:,}; other dropped: {checks['rows_other_dropped']:,}")
    L.append(f"- Kept rows: **{len(t):,}** — country feeds {int((t.level=='country').sum()):,}, "
             f"region feeds {int((t.level=='region').sum()):,}")
    L.append(f"- Countries: {t.country_code.nunique()}; locations: {t.location.nunique():,}")
    L.append(f"- Start times (UTC): {t.start_time_utc.min()} → {t.start_time_utc.max()}")
    L.append(f"- Missing end time: {int(t.end_time_utc.isna().sum()):,} rows "
             f"({t.end_time_utc.isna().mean():.1%}) — trends still active when scraped")
    L.append(f"- Start times in the ambiguous autumn DST hour (assumed CEST): {checks['dst_ambiguous_start_rows']:,}")
    day = t.start_time_utc.dt.floor("D")
    per_day = day.value_counts().sort_index()
    full = pd.date_range(per_day.index.min(), per_day.index.max(), freq="D", tz="UTC")
    per_day = per_day.reindex(full, fill_value=0)
    med = per_day.median()
    gaps = per_day[per_day < 0.25 * med]
    L.append(f"- Rows per day: median {med:,.0f}. Days with < 25% of the median ({len(gaps)} days, "
             f"likely collection gaps):\n")
    if len(gaps):
        runs, start, prev = [], None, None
        for d in gaps.index:
            if prev is not None and (d - prev).days == 1:
                prev = d
                continue
            if start is not None:
                runs.append((start, prev))
            start = prev = d
        runs.append((start, prev))
        L.append(md_table(pd.DataFrame([{"from": a.date(), "to": b.date(), "days": (b - a).days + 1,
                                         "rows": int(per_day[a:b].sum())} for a, b in runs])))
    cc = t[t.level == "country"].groupby("country_code").start_time_utc.agg(["min", "max", "size"])
    late = cc[(cc["min"] > per_day.index.min() + pd.Timedelta(days=30)) | (cc["max"] < per_day.index.max() - pd.Timedelta(days=30))]
    if len(late):
        L.append("\nCountry feeds that start late or stop early (> 30 days from the dataset edges):\n")
        L.append(md_table(late.reset_index().rename(columns={"size": "rows"}).assign(
            min=lambda d: d["min"].dt.date, max=lambda d: d["max"].dt.date)))
    L.append("")

    # --- timestamp checks
    L.append("## Timestamp checks\n")
    L.append("Times in the source are wall-clock Central European time (labelled otherwise); they are "
             "localized to `Europe/Berlin` and converted to UTC. Each check takes the earliest start of the "
             "string on the event's UTC date; tolerance ±15 min.\n")
    L.append(md_table(pd.DataFrame(checks["checks"])))
    L.append("\nNote: “pope francis” also trended on 2025-04-20 (his Easter appearance, and a small US-CA "
             "trend earlier); those rows are excluded by restricting the check to the event date.\n")

    # --- merging
    L.append("## Merging statistics\n")
    layers = comb.get("layers", {})
    L.append(f"- Distinct raw strings (`query_raw`): **{comb.get('distinct_raw', 0):,}**")
    L.append(f"- Distinct normalized strings (`query_norm`): **{comb.get('distinct_norm', 0):,}** "
             f"(normalization merged {comb.get('distinct_raw', 0) - comb.get('distinct_norm', 0):,})")
    L.append(f"- Topics: **{comb.get('topics', 0):,}**; largest group {comb.get('max_group_size')} strings "
             "(fuzzy/semantic merges capped at 50 strings)")
    L.append(f"- Multi-string topics: {int((st.groupby('topic_id').size() > 1).sum()):,}; strings in them: "
             f"{int(st.topic_id.map(st.topic_id.value_counts()).gt(1).sum()):,}\n")
    rows = [{"layer": "normalization (exact query_norm)", "unions": comb.get("distinct_raw", 0) - comb.get("distinct_norm", 0),
             "refused_cannot_link": "", "refused_claude_name_differs": "", "refused_size_cap": ""}]
    for name in ("wikidata", "claude", "typo", "semantic"):
        c = layers.get(name)
        if c:
            rows.append({"layer": name, "unions": c["merged"], "refused_cannot_link": c["cannot_link"],
                         "refused_claude_name_differs": c.get("claude_name_differs", ""),
                         "refused_size_cap": c["size_cap"]})
        else:
            rows.append({"layer": name, "unions": 0, "refused_cannot_link": "not run",
                         "refused_claude_name_differs": "", "refused_size_cap": ""})
    L.append("Each union reduces the number of groups by one. Layers run in the order shown (after normalization: "
             "Wikidata, Claude, typo, semantic); a pair already joined by an earlier layer counts for that layer.\n")
    L.append(md_table(pd.DataFrame(rows)))
    tf = layers.get("typo_filter")
    if tf:
        L.append(f"\nTypo edges before the union-find: {tf['edges_in']:,}; dropped because a string has <= 8 "
                 f"characters and similarity < 0.96: {tf['dropped_short']:,}; dropped because both strings have "
                 f"confident (>= 0.5) Claude names that differ: {tf['dropped_claude_names_differ']:,}; "
                 f"kept: {tf['edges_kept']:,}.")
    L.append("")

    # --- wikidata
    L.append("## Wikidata\n")
    chk_p, nl_p = WORK / "wikidata_claude_check.parquet", WORK / "wikidata_name_lookup.parquet"
    if chk_p.exists():
        c = pd.read_parquet(chk_p)
        L.append(f"- Claude QIDs checked with `wbgetentities`: {len(c):,} strings "
                 f"({c.claude_qid.nunique():,} distinct ids)\n")
        L.append(md_table(c.status.value_counts().rename_axis("status").reset_index(name="strings")))
    else:
        L.append("- Claude QIDs not verified yet.")
    if nl_p.exists():
        n = pd.read_parquet(nl_p)
        L.append(f"\n- English-name lookup (`wbsearchentities`, exact label/alias): {len(n):,} strings, "
                 f"{n.name.nunique():,} distinct names\n")
        L.append(md_table(n.status.value_counts().rename_axis("status").reset_index(name="strings")))
    else:
        L.append("- English-name lookup not run yet.")
    L.append(f"\n- Strings with a QID used for merging: {comb.get('strings_with_qid', 0):,}\n")

    # --- claude
    L.append("## Claude labelling\n")
    spent = sum(b.get("cost_usd") or 0 for b in log["batches"])
    tin = sum((b.get("usage") or {}).get("input_tokens", 0) for b in log["batches"])
    tout = sum((b.get("usage") or {}).get("output_tokens", 0) for b in log["batches"])
    lab = st[st.canonical_en.notna()]
    L.append(f"- Strings labelled: **{len(lab):,}** of {int(st.important.sum()):,} important strings")
    L.append(f"- Batches: {len(log['batches'])}; tokens in {tin:,}, out {tout:,}; **total API cost ${spent:.4f}**")
    if len(lab):
        L.append(f"- Answered “unknown”: {int((lab.canonical_en.str.lower() == 'unknown').sum())}; "
                 f"with a Wikidata QID: {int(lab.claude_qid.notna().sum())} "
                 f"(unverified, not used: {int(st.claude_qid_unverified.notna().sum())})\n")
        L.append(md_table(lab.type.value_counts().rename_axis("type").reset_index(name="strings")))
        L.append("")
        L.append(md_table(lab.intent.value_counts().rename_axis("intent").reset_index(name="strings")))
    L.append("")

    # --- top topics
    L.append("## 20 biggest topics\n")
    rows_per = st.groupby("topic_id").n_rows.sum().sort_values(ascending=False).head(20)
    out = []
    for tid, n in rows_per.items():
        g = st[st.topic_id == tid].sort_values("n_rows", ascending=False)
        out.append({"topic_id": tid, "topic_name": g.topic_name.iloc[0], "rows": int(n), "strings": len(g),
                    "phrasings (most common first)": "; ".join(g.query_norm.head(8))})
    L.append(md_table(pd.DataFrame(out)))
    L.append("")

    # --- questionable merges
    L.append("## 10 merges that look questionable\n")
    L.append("Selected automatically: the lowest-similarity semantic merges, and typo/semantic merges "
             "inside the largest multi-string groups. Each row is one accepted edge.\n")
    s = pd.read_parquet(WORK / "strings.parquet", columns=["sid", "query_norm"])
    q = s.query_norm.values
    sem = pd.read_parquet(WORK / "edges_semantic.parquet")
    typ = pd.read_parquet(WORK / "edges_typo.parquet")
    grp_size = st.set_index("sid").topic_id.map(st.topic_id.value_counts())
    sem["group_size"] = sem.a.map(grp_size)
    typ["group_size"] = typ.a.map(grp_size)
    cand = pd.concat([
        sem.sort_values("cos").head(4).assign(layer="semantic", score=lambda d: d.cos.round(3)),
        sem[sem.rule == "high_cos+added_words+related"].sort_values(["group_size", "cos"], ascending=[False, True]).head(3)
           .assign(layer="semantic (added words)", score=lambda d: d.cos.round(3)),
        typ.sort_values(["score", "group_size"], ascending=[True, False]).head(3).assign(layer="typo", score=lambda d: d.score),
    ])
    cand["string_a"], cand["string_b"] = q[cand.a], q[cand.b]
    cand["topic"] = cand.a.map(st.set_index("sid").topic_name)
    L.append(md_table(cand[["layer", "score", "string_a", "string_b", "topic", "group_size"]]))
    L.append("")
    # --- moments
    msum = load_json(WORK / "moments_summary.json")
    mp = INTERIM / "moments.parquet"
    if msum and mp.exists():
        m = pd.read_parquet(mp, columns=["moment_id", "topic_name", "type", "start_utc", "reach", "reach_60",
                                         "minutes_to_half", "peak_volume", "is_global"])
        L.append("## Moments\n")
        L.append(f"- National trend rows: {msum['national_rows']:,}; topics: {msum['topics']:,}; "
                 f"sessions: {msum['sessions']:,}; moments: **{msum['moments']:,}** (a country's session ends after "
                 f"{msum['session_gap_hours']} h without the topic; a moment is a burst of session starts with gaps "
                 f"≤ {msum['burst_gap_hours']} h)")
        L.append(f"- Moments lasting ≥ 7 days: {msum['moments_longer_than_7d']:,}")
        L.append(f"- Topics with more than one moment: {msum['topics_with_multiple_moments']:,}")
        L.append(f"- Moments reaching ≥ 2 countries: {msum['moments_reach_ge_2']:,}; ≥ 10: {msum['moments_reach_ge_10']:,}")
        L.append(f"- Global moments ({msum['global_rule']}): **{msum['global_moments']:,}** "
                 f"(top 300 in `docs/GLOBAL_MOMENTS.md`); excluding matches and clubs: "
                 f"{msum['global_moments_non_sport']:,}\n")
        g = m[m.is_global].sort_values(["reach_60", "reach"], ascending=False).head(20)
        L.append("## 20 biggest global moments\n")
        L.append(md_table(g.assign(start_utc=g.start_utc.dt.strftime("%Y-%m-%d %H:%M"),
                                   minutes_to_half=g.minutes_to_half.astype(int))
                          [["topic_name", "type", "start_utc", "reach_60", "reach", "minutes_to_half"]]))
        L.append("")

    # --- exports
    man = load_json(INTERIM.parent / "export" / "manifest.json")
    if man:
        L.append("## Exports\n")
        big = max(man["files"], key=lambda f: f["bytes"])
        L.append(f"- {len(man['files'])} files, {man['total_bytes'] / 1e6:.1f} MB; largest `{big['file']}` "
                 f"{big['bytes'] / 1e6:.2f} MB (limit {man['max_bytes'] / 1e6:.0f} MB)\n")
    (DOCS / "PROFILE.md").write_text("\n".join(L))
    print(f"wrote {DOCS/'PROFILE.md'}")


if __name__ == "__main__":
    main()
